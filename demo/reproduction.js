#!/usr/bin/env node
// Local end-to-end fixture demo. No configured environment is read or modified.
// node demo/reproduction.js [--keep]
// DT_TEST_DB_URL=postgres://.../postgres node demo/reproduction.js [--keep]
const fs = require('fs');
const os = require('os');
const path = require('path');
const assert = require('node:assert/strict');
const keep = process.argv.slice(2).includes('--keep');
const unknown = process.argv.slice(2).filter(a => a !== '--keep');
if (unknown.length) { process.stderr.write(`unknown demo options: ${unknown.join(', ')}\n`); process.exit(1); }

const scratchUrl = process.env.DT_TEST_DB_URL;
const home = fs.mkdtempSync(path.join(os.tmpdir(), 'dt-reproduction-demo-'));
// Set these before loading any dt modules. An inherited cache/work/plugin override must
// never redirect the demo into the user's normal configuration or writable checkout.
for (const key of Object.keys(process.env)) if (/^DT_(?:.*_DIR|HOME|TOOLS|TEST_RUNNER_URL)$/.test(key)) delete process.env[key];
process.env.DT_HOME = home;
process.env.DT_GIT_DIR = path.join(home, 'git');
process.env.DT_RATE_PER_SEC = '0';
const write = (rel, value) => { const file = path.join(home, rel); fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, JSON.stringify(value, null, 2)); };
write('config.json', { envs: { demo: { postgres: { orders: 'postgres://demo:demo@127.0.0.1:1/orders', billing: 'postgres://demo:demo@127.0.0.1:1/billing' } } }, ...(scratchUrl ? { tests: { pgUrl: scratchUrl } } : {}) });
const R = require('../lib/reproduction');
const emit = (step, data) => process.stdout.write(JSON.stringify({ step, ...data }) + '\n');
const column = (name, type = 'bigint') => ({ name, type, nullable: false });
const table = (schema, name, columns, pk, fks = []) => ({ schema, name, kind: 'table', columns, constraints: [{ name: `${name}_pk`, type: 'p', def: `PRIMARY KEY (${pk.join(', ')})` }, ...fks] });
const foreign = (name, columns, ref, refs) => ({ name, type: 'f', ref, def: `FOREIGN KEY (${columns.join(', ')}) REFERENCES ${ref}(${refs.join(', ')})` });
const syncedAt = '2026-10-28T00:00:00.000Z';
write('cache/demo/pg/orders.json', { db: 'orders', syncedAt, tables: [
  table('sales', 'orders', [column('id'), column('tenant_id'), column('customer_id'), column('email', 'text'), column('tags', 'text[]')], ['id'], [foreign('order_customer_fk', ['tenant_id', 'customer_id'], 'sales.customers', ['tenant_id', 'id'])]),
  table('sales', 'customers', [column('tenant_id'), column('id'), column('email', 'text')], ['tenant_id', 'id']),
], functions: [] });
write('cache/demo/pg/billing.json', { db: 'billing', syncedAt, tables: [
  table('pay', 'payments', [column('id'), column('order_id'), column('status', 'text'), column('amount', 'numeric(12,2)')], ['id'], [foreign('payment_status_fk', ['status'], 'pay.d_status', ['code'])]),
  table('pay', 'd_status', [column('code', 'text')], ['code']),
], functions: [] });
write('cache/demo/kafka/order_paid.json', { topic: 'order_paid', valueSchema: { type: 'JSON', version: 1, schema: { type: 'object', properties: { orderId: { type: 'integer' }, email: { type: 'string' } }, required: ['orderId'] } } });
const workspace = 'reproduction-demo';
const workspacePath = path.join(home, 'work', workspace);
fs.mkdirSync(workspacePath, { recursive: true });
write(`cache/work/${workspace}.json`, { id: workspace, path: workspacePath, createdAt: syncedAt });
const records = {
  'orders:sales.orders': [{ id: 42, tenant_id: 7, customer_id: 9, email: 'alice@example.test', tags: ['paid', 'demo'] }],
  'orders:sales.customers': [{ tenant_id: 7, id: 9, email: 'alice@example.test' }, { tenant_id: 8, id: 9, email: 'other@example.test' }],
  'billing:pay.payments': [{ id: 80, order_id: 42, status: 'PAID', amount: '12.50' }],
  'billing:pay.d_status': [{ code: 'PAID' }],
};
const sourceEvents = [
  { partition: 0, offset: '100', timestamp: syncedAt, key: '42', headers: { authorization: 'demo-secret' }, value: { orderId: 42, email: 'alice@example.test', status: 'PAID' } },
  { partition: 0, offset: '100', timestamp: syncedAt, key: '42', headers: { authorization: 'demo-secret' }, value: { orderId: 42, email: 'alice@example.test', status: 'PAID' } },
  { partition: 1, offset: '200', timestamp: syncedAt, key: '999', headers: {}, value: { orderId: 999, email: 'other@example.test', status: 'PAID' } },
];
const queryTrace = [];
async function query(db, sql, params) {
  // A deliberately small read-only adapter for the SQL generated by reproduction.capture.
  // Production capture uses lib/pg's guarded, parameterized read-only transactions.
  const match = sql.match(/^select \* from "([^"]+)"\."([^"]+)" where (.+) order by .+ limit (\d+)$/);
  if (!match) throw new Error('synthetic demo adapter accepts only bounded generated SELECT statements');
  const id = `${db}:${match[1]}.${match[2]}`, limit = Number(match[4]);
  const clauses = match[3].split(' or ').map(s => s.replace(/^\(|\)$/g, '').split(' and ').map(s => {
    const term = s.match(/^"([^"]+)" = \$(\d+)$/), nil = s.match(/^"([^"]+)" is null$/);
    if (!term && !nil) throw new Error('unsupported synthetic predicate');
    return term ? [term[1], params[Number(term[2]) - 1]] : [nil[1], null];
  }));
  const rows = (records[id] || []).filter(row => clauses.some(terms => terms.every(([col, value]) => value === null ? row[col] == null : String(row[col]) === String(value)))).slice(0, limit);
  queryTrace.push({ db, table: `${match[1]}.${match[2]}`, parameters: params.length, limit, rows: rows.length });
  return structuredClone(rows);
}
async function messages(topic, { maxMessages }) {
  assert.equal(topic, 'order_paid');
  return { messages: structuredClone(sourceEvents.slice(0, maxMessages)), windows: [{ partition: 0, low: '100', from: '100', next: '101', highExclusive: '101', count: 1 }, { partition: 1, low: '200', from: '200', next: '201', highExclusive: '201', count: 1 }], truncated: sourceEvents.length > maxMessages };
}
const input = { env: 'demo', seeds: [{ db: 'orders', table: 'sales.orders', where: { id: 42 } }],
  relations: [{ from: { db: 'orders', table: 'sales.orders', columns: ['id'] }, to: { db: 'billing', table: 'pay.payments', columns: ['order_id'] }, required: true, evidence: 'synthetic PaymentListener: payment.order_id comes from order.id' }],
  topics: [{ topic: 'order_paid', matches: [{ path: 'value.orderId', from: { db: 'orders', table: 'sales.orders', column: 'id' } }] }],
  limits: { depth: 5, rowsPerTable: 20, totalRows: 50, queries: 20, messagesPerTopic: 10 } };

async function main() {
  emit('environment', { isolated: true, home, replayRequested: !!scratchUrl, retained: keep });
  const plan = R.plan(input);
  emit('plan', { tables: plan.tables.map(t => t.id), relations: plan.relations.map(r => ({ from: `${r.from.db}:${r.from.table}`, to: `${r.to.db}:${r.to.table}`, source: r.source })), limits: plan.limits });
  const captured = await R.capture(input, { query, messages });
  assert.equal(captured.complete, true, JSON.stringify(captured.gaps));
  assert.equal(captured.rows['orders:sales.customers'].length, 1, 'composite FK excludes the other tenant');
  const order = captured.rows['orders:sales.orders'][0], payment = captured.rows['billing:pay.payments'][0], event = captured.events.order_paid.messages[0];
  assert.equal(order.id, payment.order_id); assert.equal(order.id, event.value.orderId);
  assert.equal(order.email, event.value.email); assert.notEqual(order.email, 'alice@example.test');
  assert.equal(captured.events.order_paid.messages.length, 1, 'duplicate and unrelated events are excluded');
  emit('capture', { complete: captured.complete, counts: captured.counts, sharedOrderId: order.id, maskedEmail: order.email, queryTrace, gaps: captured.gaps });
  const captureId = R.save(captured);
  const exported = R.exportFixture(workspace, captured, { name: 'paid-order' });
  const verified = R.loadFixture(workspace, exported.path);
  emit('export', { workspace, path: path.join(workspacePath, exported.path), databases: Object.keys(verified.databases), topics: Object.keys(verified.topics), files: exported.files, hashesVerified: true });
  const E = require('../lib/experiments');
  E.save({ id: 'paid-order', tools: [], code: 'const f = vars.fixture; const order = f.rows["orders:sales.orders"][0]; const payment = f.rows["billing:pay.payments"][0]; const event = f.events.order_paid.messages[0]; test("payment joins order", () => expect(payment.order_id).toBe(order.id)); test("Kafka joins order", () => expect(event.value.orderId).toBe(order.id)); return { orderId: order.id, amount: payment.amount, status: event.value.status };' });
  const experiment = await E.run('paid-order', { capture: captureId });
  assert.equal(experiment.ok, true, experiment.error);
  emit('experiment', { id: 'paid-order', allowlist: [], ok: experiment.ok, assertions: experiment.tests, value: experiment.value });
  if (scratchUrl) {
    const replay = await R.replay(workspace, exported.path);
    try { emit('replay', { validated: true, databases: Object.keys(replay.databases), topics: Object.keys(replay.topics) }); }
    finally { await replay.cleanup(); emit('scratch-cleanup', { dropped: true }); }
  } else emit('replay', { skipped: true, reason: 'Set DT_TEST_DB_URL to an isolated scratch Postgres to validate real SQL and constraints.' });
}
main().catch(error => { emit('error', { error: error.message }); process.exitCode = 1; }).finally(() => {
  if (!keep) fs.rmSync(home, { recursive: true, force: true });
  emit('cleanup', { home, removed: !keep, ...(keep ? { inspect: path.join(workspacePath, 'src/test/resources/dt-fixtures/paid-order') } : {}) });
});
