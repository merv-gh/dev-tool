// Builds dist/: one bundled dt.js (code + node_modules) plus the files it reads at runtime.
// docker-compose runs dist/ in a stock node image, so there is no image to build.
//   node build.js           write dist/
//   node build.js --check   exit 1 if dist/ is not what the sources build to
const fs = require('fs');
const path = require('path');
const esbuild = require('esbuild');

const ROOT = __dirname;
const DIST = path.join(ROOT, 'dist');
const check = process.argv.includes('--check');

const bundle = esbuild.buildSync({
  entryPoints: [path.join(ROOT, 'cli.js')], bundle: true, platform: 'node', target: 'node22', format: 'cjs',
  write: false, legalComments: 'none', logLevel: 'error',
  external: ['*.node', 'cpu-features'], // ssh2's optional native speedups; it falls back to plain JS without them
  banner: { js: '#!/usr/bin/env node\n// Generated by build.js from the sources in this repo; do not edit.' },
}).outputFiles[0].text.replace(/^#!.*\n(?=#!)/, ''); // cli.js has its own shebang

const files = { 'dt.js': bundle };
for (const f of fs.readdirSync(path.join(ROOT, 'web'))) files[`web/${f}`] = fs.readFileSync(path.join(ROOT, 'web', f));
files['agent-prompt.md'] = fs.readFileSync(path.join(ROOT, 'lib', 'agent-prompt.md'));
files['config.example.json'] = fs.readFileSync(path.join(ROOT, 'config.example.json'));

const stale = Object.entries(files).filter(([f, data]) => {
  try { return !fs.readFileSync(path.join(DIST, f)).equals(Buffer.from(data)); } catch { return true; }
}).map(([f]) => f);
if (check) {
  if (stale.length) { console.error(`dist/ is stale (${stale.join(', ')}): run npm run build`); process.exit(1); }
  console.log('dist/ is up to date');
} else {
  for (const f of stale) {
    fs.mkdirSync(path.dirname(path.join(DIST, f)), { recursive: true });
    fs.writeFileSync(path.join(DIST, f), files[f], f === 'dt.js' ? { mode: 0o755 } : undefined);
  }
  console.log(`dist/: ${Object.keys(files).length} files, ${stale.length} changed, dt.js ${(bundle.length / 1024).toFixed(0)} KB`);
}
