// The Playwright MCP container reads its secrets from a dotenv file. dt writes it from config:
// every name listed in browser.sites.*.secrets, with its value from .env. Nothing else goes in.
const fs = require('fs');
const path = require('path');
const { PATHS, getBrowser } = require('./config');

const FILE = path.join(PATHS.cache, 'browser.env');
const quote = (v) => (/^[\w@%+=:,./-]*$/.test(v) ? v : !v.includes("'") ? `'${v}'` : JSON.stringify(v));

function writeSecrets() {
  const vals = getBrowser().secretValues();
  const text = '# generated by dt from config.json browser.sites + .env; edit those instead\n' +
    Object.entries(vals).map(([k, v]) => `${k}=${quote(String(v))}`).join('\n') + '\n';
  fs.mkdirSync(path.dirname(FILE), { recursive: true });
  let old = null;
  try { old = fs.readFileSync(FILE, 'utf8'); } catch {}
  if (old !== text) fs.writeFileSync(FILE, text, { mode: 0o600 });
  try { fs.chmodSync(FILE, 0o600); } catch {} // run.sh creates it empty with the default mode
  return { file: FILE, names: Object.keys(vals), changed: old !== text };
}

module.exports = { writeSecrets, FILE };
