// Deterministic local assets: no CDN, extension host, or runtime package installation.
const fs = require('node:fs'), path = require('node:path'), esbuild = require('esbuild');
const root = path.resolve(__dirname, '..'), out = path.join(root, 'web/vendor/workbench');
function generate({ check = false } = {}) {
  const options = { bundle: true, minify: true, target: 'es2022', format: 'iife', platform: 'browser', legalComments: 'eof', write: false, logLevel: 'error', outdir: out, loader: { '.ttf': 'file' }, assetNames: '[name]' };
  const result = esbuild.buildSync({ ...options, entryPoints: { workbench: path.join(root, 'web/workbench-entry.js'), worker: path.join(root, 'node_modules/monaco-editor/esm/vs/editor/editor.worker.js') } });
  const files = result.outputFiles.map(f => [f.path, f.contents]);
  files.push([path.join(out, 'monaco-LICENSE.txt'), fs.readFileSync(path.join(root, 'node_modules/monaco-editor/LICENSE'))]);
  files.push([path.join(out, 'headless-tree-LICENSE.txt'), fs.readFileSync(path.join(root, 'dev/licenses/headless-tree.txt'))]);
  files.push([path.join(out, 'README.md'), Buffer.from('Generated by `node dev/build-workbench.js`. Monaco Editor 0.57.0 and Headless Tree Core 1.8.0, MIT. Same-origin assets and worker; no Java language server or VS Code extension host.\n')]);
  for (const [file, data] of files) {
    if (check) { if (!fs.existsSync(file) || !fs.readFileSync(file).equals(Buffer.from(data))) throw Error('Stale workbench assets: run node dev/build-workbench.js'); }
    else { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, data); }
  }
}
if (require.main === module) generate({ check: process.argv.includes('--check') });
module.exports = { generate };
